#ifndef TTT_CHARACTER_IDS_H
#define TTT_CHARACTER_IDS_H
#include <stdint.h>
#define TTT_CHARACTER_COUNT 47u
/* Ordem exata do mapa de 47 slots do EBOOT V0.4. IDs de combate (nao IDs do menu). */
static const uint8_t ttt_character_battle_ids[47] = {
    0x00u, 0x01u, 0x02u, 0x07u, 0x08u, 0x09u, 0x0Au, 0x0Bu, 0x0Cu, 0x14u, 0x16u, 0x18u,
    0x1Eu, 0x1Fu, 0x20u, 0x21u, 0x26u, 0x2Bu, 0x30u, 0x33u, 0x36u, 0x37u, 0x39u, 0x3Au,
    0x3Bu, 0x3Cu, 0x3Du, 0x3Eu, 0x3Fu, 0x40u, 0x41u, 0x42u, 0x43u, 0x44u, 0x45u, 0x48u,
    0x4Au, 0x4Bu, 0x4Cu, 0x4Eu, 0x51u, 0x60u, 0x61u, 0x62u, 0x6Eu, 0x71u, 0x73u
};
static inline uint8_t ttt_character_battle_id(unsigned slot){
    return slot<TTT_CHARACTER_COUNT?ttt_character_battle_ids[slot]:0xffu;
}
#endif
